const weekdaysFullKm = ['អាទិត្យ', 'ចន្ទ', 'អង្គារ', 'ពុធ', 'ព្រហស្បតិ៍', 'សុក្រ', 'សៅរ៍'];
const weekdaysFullEn = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];
const weekdaysMonKm = ['ចន្ទ', 'អង្គារ', 'ពុធ', 'ព្រហ.', 'សុក្រ', 'សៅរ៍', 'អាទិត្យ'];
const weekdaysMonEn = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'];

Lang deviceLang() {
  try {
    final locale = WidgetsBinding.instance.platformDispatcher.locale.languageCode;
    return locale.toLowerCase().startsWith('km') ? Lang.km : Lang.en;
  } catch (_) {
    return Lang.km;
  }
}

